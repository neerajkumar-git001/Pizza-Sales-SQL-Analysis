-- BASIC QUESTIONS 

--1) Retrieve the total number of orders placed.
SELECT
	COUNT(ORDER_ID) AS TOTAL_ORDERS
FROM
	ORDERS;



-- 2) Calculate the total revenue generated from pizza sales.
SELECT
	SUM(O.QUANTITY * P.PRICE)::DECIMAL(10, 2) AS TOTAL_REVENUE
FROM
	ORDER_DETAILS AS O
	RIGHT JOIN PIZZAS AS P USING (PIZZA_ID);



-- 3) Identify the highest-priced pizza.
SELECT
	P1.NAME AS NAME,
	P2.PRICE AS PIZZA_PRICE
FROM
	PIZZA_TYPES AS P1
	LEFT JOIN PIZZAS AS P2 USING (PIZZA_TYPE_ID)
ORDER BY
	P2.PRICE DESC LIMIT 1;


-- 4) Identify the most common pizza size ordered.
SELECT
	P.SIZE,
	COUNT(OD.ORDER_DETAILS_ID) AS ORDER_COUNT
FROM
	PIZZAS AS P
	LEFT JOIN ORDER_DETAILS AS OD USING (PIZZA_ID)
GROUP BY
	P.SIZE
ORDER BY
	 COUNT(OD.ORDER_DETAILS_ID) DESC
	LIMIT 1 ;



-- 5) List the top 5 most ordered pizza types along with their quantities.

SELECT
	P.NAME AS PIZZA_NAME,
	SUM(OD.QUANTITY) AS QUANTITY
FROM
	PIZZA_TYPES AS P
	LEFT JOIN PIZZAS AS P1 USING (PIZZA_TYPE_ID)
	LEFT JOIN ORDER_DETAILS AS OD USING (PIZZA_ID)
GROUP BY
	PIZZA_NAME
ORDER BY
	QUANTITY DESC
LIMIT
	5 ;




