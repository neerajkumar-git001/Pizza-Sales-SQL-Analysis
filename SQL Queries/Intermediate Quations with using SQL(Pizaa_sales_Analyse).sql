
-- INTERMEDIATE QUESTIONS

-- 1)Join the necessary tables to find the total quantity of each pizza category ordered.
SELECT
	PT.CATEGORY AS CATEGORY,
	SUM(OD.QUANTITY) AS TOTAL_QUANTITY
FROM
	PIZZA_TYPES AS PT
	LEFT JOIN PIZZAS AS P USING (PIZZA_TYPE_ID)
	LEFT JOIN ORDER_DETAILS AS OD USING (PIZZA_ID)
GROUP BY
	CATEGORY



-- 2)Determine the distribution of orders by hour of the day.
SELECT
	EXTRACT(
		HOUR
		FROM
			TIME
	) AS HOUR,
	COUNT(OD.QUANTITY) AS ORDER_COUNT
FROM
	ORDERS AS O
	LEFT JOIN ORDER_DETAILS AS OD USING (ORDER_ID)
GROUP BY
	HOUR;



-- 3) Join relevant tables to find the category-wise distribution of pizzas.
SELECT PT.CATEGORY AS CATEGORY, SUM(OD.QUANTITY) AS QUANTITY
FROM PIZZA_TYPES AS PT 
LEFT JOIN PIZZAS AS P USING(PIZZA_TYPE_ID)
LEFT JOIN ORDER_DETAILS AS OD USING(PIZZA_ID)
GROUP BY CATEGORY;




-- 4)Group the orders by date and calculate the average number of pizzas ordered per day.

SELECT
	O.DATE AS DATE,
	SUM(OD.QUANTITY)::DECIMAL(7, 2) AS PER_DAY_PIZZA
FROM
	ORDERS AS O
	LEFT JOIN ORDER_DETAILS AS OD USING (ORDER_ID)
GROUP BY
	DATE
ORDER BY
	DATE;


-- 5)Determine the top 3 most ordered pizza types based on revenue.
SELECT
	PT.NAME AS NAME,
	SUM(P.PRICE * OD.QUANTITY)::DECIMAL(7, 2) AS REVENUE
FROM
	PIZZA_TYPES AS PT
	LEFT JOIN PIZZAS AS P USING (PIZZA_TYPE_ID)
	LEFT JOIN ORDER_DETAILS AS OD USING (PIZZA_ID)
GROUP BY
	NAME
ORDER BY
	REVENUE DESC
LIMIT
	3;



