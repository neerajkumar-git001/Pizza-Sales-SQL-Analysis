-- 1) Calculate the percentage contribution of each pizza type to total revenue

SELECT PT.CATEGORY AS CATEGORY, ROUND(
		( SUM(OD.QUANTITY * P.PRICE)::DECIMAL(10, 2) / (
		SELECT SUM(OD.QUANTITY * P.PRICE)::DECIMAL(10, 2) AS TOTAL_SALES
		FROM
		   PIZZAS AS P LEFT JOIN ORDER_DETAILS AS OD USING (PIZZA_ID))) * 100, 2 ) AS CONTRIBUTE_PERCENTAGE
FROM
	PIZZA_TYPES AS PT
	LEFT JOIN PIZZAS AS P USING (PIZZA_TYPE_ID)
	LEFT JOIN ORDER_DETAILS AS OD USING (PIZZA_ID)
GROUP BY CATEGORY
ORDER BY CONTRIBUTE_PERCENTAGE DESC;


-- TOTAL SALES
SELECT  SUM(OD.QUANTITY * P.PRICE):: DECIMAL(10,2) AS TOTAL_SALES
FROM PIZZAS AS P
LEFT JOIN ORDER_DETAILS AS OD 
USING (PIZZA_ID)




-- 2) Analyze the cumulative revenue generated over time.
SELECT DATE,SUM(REVENUE) OVER(ORDER BY DATE) AS CUM_REVENUE
FROM
	(SELECT O.DATE AS DATE, SUM(OD.QUANTITY* P.PRICE)::DECIMAL(10,2) AS REVENUE
FROM ORDERS AS O
	LEFT JOIN ORDER_DETAILS AS OD USING(ORDER_ID)
	RIGHT JOIN PIZZAS AS P USING(PIZZA_ID)
	GROUP BY DATE
	ORDER BY DATE) AS SALES_DATA;


-- 3) Determine the top 3 most ordered pizza types based on revenue for each pizza category.
SELECT CATEGORY,NAME,REVENUE
FROM
 (
	SELECT CATEGORY, NAME,REVENUE,RANK() OVER (
				PARTITION BY CATEGORY ORDER BY REVENUE DESC) AS RN
FROM
 (   SELECT PT.CATEGORY AS CATEGORY, PT.NAME AS NAME, SUM(OD.QUANTITY * P.PRICE)::DECIMAL(10, 2) AS REVENUE
				FROM
					PIZZA_TYPES AS PT
					LEFT JOIN PIZZAS AS P USING (PIZZA_TYPE_ID)
					LEFT JOIN ORDER_DETAILS AS OD USING (PIZZA_ID)
				GROUP BY CATEGORY, NAME
				ORDER BY CATEGORY, NAME ) AS R ) AS N
WHERE RN <= 3;

